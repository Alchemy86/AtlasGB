STRUCTS = [
    (
        "party_struct",
        "wPartyMon1",
        "wPartyMon2",
        "One of the six Pokemon you carry. Also the shape the link cable sends, "
        "and the shape a trainer's team is built in.",
    ),
    (
        "box_struct",
        "wBoxMon1",
        "wBoxMon2",
        "One of the twenty in a PC box: `party_struct` with the level and the five "
        "computed stats removed, because a stored Pokemon's stats are recalculated "
        "when it is withdrawn.",
    ),
    (
        "battle_struct",
        "wBattleMon",
        None,
        "The active Pokemon while a battle runs. Not the party shape: original "
        "trainer, experience and stat experience are gone, so the level and the "
        "stats sit at different offsets. Confusing the two is the classic way to "
        "produce a level 6,400 Pokemon.",
    ),
    (
        "battle_struct (opponent)",
        "wEnemyMon",
        None,
        "The same 29 bytes for the other side.",
    ),
    (
        "day-care lodger",
        "wDayCareMon",
        None,
        "One `box_struct` on its own, with its name and OT beside it.",
    ),
]


def struct_block(rows) -> str:
    by_symbol = {r["symbol"]: r for r in rows}
    out = []
    for title, first, second, blurb in STRUCTS:
        base = by_symbol.get(first)
        if base is None:
            continue
        fields = [
            r
            for r in rows
            if r["symbol"].startswith(first)
            and r["symbol"] != first
            and r["region"] == base["region"]
            and r["addr_i"] >= base["addr_i"]
        ]
        # Keep only the fields of *this* slot: everything up to the next slot.
        if second and second in by_symbol:
            end = by_symbol[second]["addr_i"]
        else:
            end = max((f["addr_i"] + max(f["len_i"], 1)) for f in fields) if fields else base["addr_i"]
        fields = [f for f in fields if f["addr_i"] < end]
        fields.sort(key=lambda r: (r["addr_i"], r["symbol"]))
        total = end - base["addr_i"]
        out.append(f"### `{title}` — {total} bytes")
        out.append("")
        out.append(blurb)
        out.append("")
        out.append(f"Base `{first}` at `{base['addr']}`.")
        out.append("")
        out.append("| offset | bytes | field | notes |")
        out.append("|---:|---:|---|---|")
        seen = set()
        for f in fields:
            off = f["addr_i"] - base["addr_i"]
            names = [g["symbol"] for g in fields if g["addr_i"] == f["addr_i"]]
            if f["addr_i"] in seen:
                continue
            seen.add(f["addr_i"])
            label = " / ".join(f"`{n[len(first):] or n}`" for n in names)
            here = [g["desc"] for g in fields if g["addr_i"] == f["addr_i"] and g["desc"]]
            out.append(f"| {off} | {size(f['len_i'])} | {label} | {here[0] if here else ''} |")
        out.append("")
    return block("structs", out)


