# splicing
# ---------------------------------------------------------------------------


class MarkerLost(Exception):
    """A page that exists has lost a marker.  Refuse rather than overwrite."""


def splice(text: str, name: str, body: str, stub: str, existed: bool) -> str:
    """Replace one generated block inside `text`.

    Operates on the text it is handed, never on the file — a page may carry
    several blocks, and re-reading the file between them would leave only the
    last one applied.

    **A page that exists and has lost its marker is an error, not a rebuild.**
    Falling back to `stub` here once silently replaced twenty-one pages of
    hand-written prose with a four-line placeholder, because the marker's own
    wording had been edited and no longer matched.  The stub is only ever used
    to create a page that is not there yet.
    """
    begin, end = BEGIN.format(name), END.format(name)
    if begin not in text or end not in text:
        if existed:
            raise MarkerLost(name)
        text = stub
    i = text.index(begin)
    j = text.index(end) + len(end)
    return text[:i] + body + text[j:]


def worked_example_block(rows, symbol: str = "wPartyCount") -> str:
    """One entry, read column by column — generated so it cannot go stale.

    The README's job is to make somebody able to parse `atlas.tsv` without
    reading this script, and the fastest way to do that is one real row with
    every cell named. Typing it out by hand would make it the one line on the
    page that is allowed to be wrong.
    """
    row = next((r for r in rows if r["symbol"] == symbol), None)
    if row is None:
        return block("example", ["*(no such entry)*"])
    cols = ["region", "bank", "addr", "len", "symbol", "role", "sect", "group",
            "verify", "desc"]
    meanings = {
        "region": "which of the CPU's address ranges it is in",
        "bank": "the bank, or `-` where the region is not banked",
        "addr": "the CPU address, `$` then four uppercase hex digits",
        "len": "bytes this symbol owns before the next named address",
        "symbol": "the label, as the disassembly spells it",
        "role": "`entry`, `alias`, `instance`, `gap` or `free`",
        "sect": "the linker section it was declared in",
        "group": "our chapter — [`tools/chapters.py`](tools/chapters.py) decides it",
        "verify": "the evidence, comma separated: `rom`, `live`, `inv`",
        "desc": "what it is, in our own words — empty when nobody has written one",
    }
    raw = "\t".join(row.get(c, "") for c in cols)
    out = [
        "```text",
        "\t".join(cols),
        raw,
        "```",
        "",
        "| column | value | what it means |",
        "|---|---|---|",
    ]
    for c in cols:
        v = row.get(c, "")
        cell = f"`{v}`" if v else "*(empty)*"
        if c == "desc" and v:
            cell = v
        out.append(f"| `{c}` | {cell} | {meanings[c]} |")
    ev = row.get("verify", "")
    toks = [t for t in ev.split(",") if t]
    names = {"rom": "the cartridge names this address as an instruction operand",
             "live": "the byte changed while the cartridge ran the fixed script",
             "inv": "a named invariant proved it means what it says"}
    out += ["", f"So `{symbol}` carries **{evidence(ev)}**: "
            + "; ".join(names[t] for t in toks) + "."]
    return block("example", out)


def check_anchors() -> list[str]:
    """Every `page.md#s-…` / `#a-…` link must land on an anchor that exists.

    A plain link checker verifies that a link's *file* exists and deliberately
    does not look at fragments, so an index of 2,400 anchored links would
    otherwise be able to rot silently. It did, in the atlas's first life:
    aliases were linked before they were given anchors, and 370 links pointed
    at nothing.

    Anchors are also this repository's public URL surface — `docs/party.md#s-
    wPartyCount` is meant to be linked to from outside — so this runs on every
    build rather than only when the pages are rewritten.
    """
    import collections

    anchors: dict[str, set[str]] = collections.defaultdict(set)
    for path in sorted(os.listdir(DIR)):
        if not path.endswith(".md"):
            continue
        text = open(os.path.join(DIR, path), encoding="utf-8").read()
        for m in re.finditer(r'<a id="([^"]+)">', text):
            anchors[path].add(m.group(1))
    broken = []
    # The chapter pages and the two indexes link each other by bare filename;
    # the repository README reaches them through `docs/`.
    scan = [(os.path.join(DIR, p), "") for p in sorted(os.listdir(DIR))
            if p.endswith(".md")]
    scan.append((os.path.join(REPO, "README.md"), "docs/"))
    for path, prefix in scan:
        if not os.path.exists(path):
            continue
        text = open(path, encoding="utf-8").read()
        for m in re.finditer(r"\]\(" + re.escape(prefix) + r"([a-z0-9-]+\.md)#([^)]+)\)", text):
            target, frag = m.group(1), m.group(2)
            if frag.startswith(("s-", "a-")) and frag not in anchors.get(target, set()):
                broken.append(f"{os.path.relpath(path, REPO)} -> {prefix}{target}#{frag}")
    return broken


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    rows = read_atlas()
    jobs = []

    # The repository README is the front page and carries the headline figures,
    # so they are generated too: a README that claimed 2,898 entries while the
    # data held 2,900 would be the most visible lie in the project.
    jobs.append(
        (
            os.path.join(REPO, "README.md"),
            [("coverage", coverage_block(rows)), ("evidence", evidence_block(rows)),
             ("chapters", chapter_index_block(rows, prefix="docs/")),
             ("example", worked_example_block(rows))],
            readme_stub(),
        )
    )
    jobs.append((os.path.join(DIR, "by-address.md"),
                 [("addresses", address_index_block(rows))], index_stub("address")))
    jobs.append((os.path.join(DIR, "by-name.md"),
                 [("names", name_index_block(rows))], index_stub("name")))
    jobs.append((os.path.join(DIR, "structures.md"),
                 [("structs", struct_block(rows))], structures_stub()))
    present = {r["group"] for r in rows}
    for name in chapters_mod.CHAPTERS:
        if name not in present:
            continue
        jobs.append((os.path.join(DIR, f"{name}.md"),
                     [("table", chapter_table(rows, name))], chapter_stub(name)))

    stale = []
    for path, blocks, stub in jobs:
        rel = os.path.relpath(path, REPO)
        before = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        text = before if before is not None else stub
        for bname, body in blocks:
            try:
                text = splice(text, bname, body, stub, existed=before is not None)
            except MarkerLost as lost:
                print(f"FAIL — {rel} has no `{lost.args[0]}` marker pair.")
                print(f"  Expected: {BEGIN.format(lost.args[0])}")
                print("  The page exists, so this is not rebuilt from the stub: that would")
                print("  throw away everything written outside the markers. Put the marker")
                print("  back, or delete the page if you really want it regenerated.")
                return 1
        if text != before:
            stale.append(rel if before is not None else f"{rel} (new)")
        if not args.check:
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(text)

    broken = check_anchors()
    if broken:
        print("FAIL — the atlas pages contain dead anchor links:")
        for b in broken[:10]:
            print(f"  {b}")
        if len(broken) > 10:
            print(f"  ... and {len(broken) - 10} more")
        return 1

    if args.check:
        if stale:
            print("FAIL — the atlas pages are stale; run `make docs`:")
            for s in stale:
                print(f"  {s}")
            return 1
        print(f"OK — {len(jobs)} atlas pages match {os.path.relpath(ATLAS, REPO)}")
        return 0

    print(f"Wrote {len(jobs)} pages from {len(rows):,} atlas entries")
    return 0


